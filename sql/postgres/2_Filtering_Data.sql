/* 
AND operator – combine two boolean expressions and return true if both expressions evaluate to true.
OR operator – combine two boolean expressions and return true if either expression evaluates to true.
Limit – retrieve a subset of rows generated by a query.
Fetch– limit the number of rows returned by a query.
In – select data that matches any value in a list of values.
Between – select data that is a range of values.
Like – filter data based on pattern matching.
Is Null – check if a value is null or not.
 */

--Where – filter rows based on a specified condition.
select * from employees where employee_id = 3;

select * from employees where salary > 80000;

select * from employees where employee_id = 3 and is_active = false;

-- Find active employees earning at least 95,000
SELECT first_name, last_name, salary
FROM employees
WHERE salary >= 95000;


-- Active employees who earn over 100,000 OR were hired before 2020
SELECT first_name, salary, hire_date, is_active
FROM employees
WHERE is_active = TRUE 
  AND (salary > 100000 OR hire_date < '2020-01-01');

-- Invert a condition using NOT
SELECT first_name, is_active
FROM employees
WHERE NOT is_active;

-- Employees hired between 2022 and 2023 (inclusive)
SELECT first_name, hire_date
FROM employees
WHERE hire_date BETWEEN '2022-01-01' AND '2023-12-31';

-- Employees with specific last names
SELECT first_name, last_name
FROM employees
WHERE last_name IN ('Patel', 'Reddy', 'Rao', 'Iyer');


-- Case-sensitive search: First names starting with 'A'
SELECT first_name, email
FROM employees
WHERE first_name LIKE 'A%';

-- PostgreSQL-specific case-insensitive search: Emails containing 'sharma' or 'SHARMA'
SELECT first_name, email
FROM employees
WHERE email ILIKE '%sharma%';

-- Single-character wildcard: 5-letter first names ending in 'a' (e.g., Meera, Kavya, Sneha, Divya, Pooja)
SELECT first_name
FROM employees
WHERE first_name LIKE '____a';

-- Find employees with a recorded salary
SELECT first_name, salary
FROM employees
WHERE salary IS NOT NULL;

-- Returns rows where last_name is not 'Patel', INCLUDING rows where last_name is NULL
SELECT first_name, last_name
FROM employees
WHERE last_name IS DISTINCT FROM 'Patel';

-- Get the top 5 highest-paid employees
SELECT employee_id, first_name, last_name, salary
FROM employees
ORDER BY salary DESC
LIMIT 5;

-- Page 1: Rows 1 to 5
SELECT employee_id, first_name, salary
FROM employees
ORDER BY employee_id ASC
LIMIT 5 OFFSET 0;

-- Page 2: Skip the first 5 rows, return rows 6 to 10
SELECT employee_id, first_name, salary
FROM employees
ORDER BY employee_id ASC
LIMIT 5 OFFSET 5;

-- Page 3: Skip the first 10 rows, return rows 11 to 15
SELECT employee_id, first_name, salary
FROM employees
ORDER BY employee_id ASC
LIMIT 5 OFFSET 10;

-- SQL-standard pagination (Page 2 with 5 rows per page)
SELECT employee_id, first_name, salary
FROM employees
ORDER BY employee_id ASC
OFFSET 5 ROWS
FETCH FIRST 5 ROWS ONLY;

-- Include ties: If 2 employees tie for the 3rd highest salary, both are returned
SELECT first_name, salary
FROM employees
ORDER BY salary DESC
FETCH FIRST 3 ROWS WITH TIES;


-- Instead of OFFSET 5, filter directly from the last seen ID on Page 1 (employee_id = 5)
SELECT employee_id, first_name, salary
FROM employees
WHERE employee_id > 5
ORDER BY employee_id ASC
LIMIT 5;


-- Get a company-wide summary across all rows in the employees table
SELECT 
    COUNT(*) AS total_employees,
    SUM(salary) AS total_payroll,
    ROUND(AVG(salary), 2) AS average_salary,
    MIN(salary) AS lowest_salary,
    MAX(salary) AS highest_salary
FROM employees;

-- Summarize employee headcount and average salary by active vs. inactive status
SELECT 
    is_active,
    COUNT(*) AS headcount,
    ROUND(AVG(salary), 2) AS avg_salary
FROM employees
GROUP BY is_active;

-- Group by a calculated expression (e.g., hiring cohort by year)
SELECT 
    EXTRACT(YEAR FROM hire_date) AS hire_year,
    COUNT(*) AS hires_count,
    SUM(salary) AS cohort_payroll
FROM employees
GROUP BY EXTRACT(YEAR FROM hire_date)
ORDER BY hire_year ASC;

-- Find hire years where the company hired at least 3 people AND average salary exceeds 75,000
SELECT 
    EXTRACT(YEAR FROM hire_date) AS hire_year,
    COUNT(*) AS hires_count,
    ROUND(AVG(salary), 2) AS avg_salary
FROM employees
WHERE is_active = TRUE               -- 1. Filter individual rows first (only active staff)
GROUP BY EXTRACT(YEAR FROM hire_date) -- 2. Group remaining rows by year
HAVING COUNT(*) >= 3                 -- 3. Filter the resulting groups
   AND AVG(salary) > 75000
ORDER BY hire_year ASC;


-- Compare active vs. inactive headcounts side-by-side in a single row
SELECT 
    COUNT(*) AS total_staff,
    COUNT(*) FILTER (WHERE is_active = TRUE) AS active_staff,
    COUNT(*) FILTER (WHERE is_active = FALSE) AS inactive_staff,
    SUM(salary) FILTER (WHERE is_active = TRUE) AS active_payroll
FROM employees;


-- Categorize employees into salary bands
SELECT 
    first_name,
    last_name,
    salary,
    CASE 
        WHEN salary >= 100000 THEN 'Senior Band'
        WHEN salary >= 80000  THEN 'Mid Band'
        WHEN salary IS NULL   THEN 'Unassigned'
        ELSE 'Junior Band'
    END AS salary_tier
FROM employees
ORDER BY salary DESC;


-- Convert boolean status into readable text labels
SELECT 
    first_name,
    CASE is_active
        WHEN TRUE  THEN 'Currently Employed'
        WHEN FALSE THEN 'Alumni / Offboarded'
        ELSE 'Status Unknown'
    END AS employment_status
FROM employees;

-- Replace NULL salaries with 0 so math calculations don't break
SELECT 
    first_name,
    COALESCE(salary, 0) AS safe_salary,
    COALESCE(salary, 0) * 0.10 AS guaranteed_bonus
FROM employees;

-- Chain multiple fallbacks (e.g., check personal_email -> work_email -> default message)
SELECT 
    first_name,
    COALESCE(email, 'No Email on File') AS contact_email
FROM employees;


-- Prevent division-by-zero errors when calculating ratios
SELECT 
    first_name,
    salary / NULLIF(0, 0) AS safe_division_result -- Returns NULL instead of crashing with ERROR: division by zero
FROM employees;

-- Convert empty strings into true NULLs before using COALESCE
SELECT 
    COALESCE(NULLIF(TRIM(first_name), ''), 'Anonymous') AS clean_name
FROM employees;














